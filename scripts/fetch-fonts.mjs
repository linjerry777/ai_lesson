// Download the site's Google Fonts once and check them in, so `next build` never fetches fonts.
//
//   node scripts/fetch-fonts.mjs
//
// Same request next/font/google made (css2 API, Chrome UA → woff2 split by unicode-range), so the
// browser still downloads only the slices a page uses. Writes app/fonts/<family>/*.woff2 plus
// app/fonts/root.css (Inter, every page) and app/fonts/hub.css (the JERRY.AI hub fonts).
// Fallback faces copy the metrics next/font generated, so the swap looks the same as before.
// All families are SIL Open Font License; see app/fonts/OFL.txt.
import { mkdir, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..', 'app', 'fonts')
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36'

const FAMILIES = [
  { css: 'root', family: 'Inter', query: 'Inter:wght@100..900', dir: 'inter',
    fallback: 'src: local("Arial"); ascent-override: 90.44%; descent-override: 22.52%; line-gap-override: 0%; size-adjust: 107.12%;' },
  { css: 'hub', family: 'Noto Sans TC', query: 'Noto+Sans+TC:wght@400;500;700;900', dir: 'noto-sans-tc',
    fallback: 'src: local("Arial"); ascent-override: 110.73%; descent-override: 27.49%; line-gap-override: 0%; size-adjust: 104.76%;' },
  { css: 'hub', family: 'Noto Serif TC', query: 'Noto+Serif+TC:wght@300;400', dir: 'noto-serif-tc',
    fallback: 'src: local("Times New Roman"); ascent-override: 95.04%; descent-override: 23.62%; line-gap-override: 0%; size-adjust: 121.11%;' },
  { css: 'hub', family: 'Anton', query: 'Anton', dir: 'anton',
    fallback: 'src: local("Arial"); ascent-override: 129.7%; descent-override: 36.29%; line-gap-override: 0%; size-adjust: 90.69%;' },
  { css: 'hub', family: 'Instrument Serif', query: 'Instrument+Serif', dir: 'instrument-serif',
    fallback: 'src: local("Times New Roman"); ascent-override: 117.94%; descent-override: 36.93%; line-gap-override: 0%; size-adjust: 83.94%;' },
  { css: 'hub', family: 'JetBrains Mono', query: 'JetBrains+Mono:wght@400;500;700', dir: 'jetbrains-mono',
    fallback: 'src: local("Arial"); ascent-override: 75.79%; descent-override: 22.29%; line-gap-override: 0%; size-adjust: 134.59%;' },
]

async function get(url, as) {
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(url, { headers: { 'user-agent': UA } })
      if (!res.ok) throw new Error(`${res.status} ${url}`)
      return as === 'text' ? await res.text() : Buffer.from(await res.arrayBuffer())
    } catch (error) {
      if (attempt >= 4) throw error
      await new Promise(resolve => setTimeout(resolve, 1000 * attempt))
    }
  }
}

const out = { root: [], hub: [] }
let files = 0
let bytes = 0
for (const spec of FAMILIES) {
  const css = await get(`https://fonts.googleapis.com/css2?family=${spec.query}&display=swap`, 'text')
  const dir = path.join(ROOT, spec.dir)
  await rm(dir, { recursive: true, force: true })
  await mkdir(dir, { recursive: true })
  const blocks = [...css.matchAll(/(?:\/\*\s*([^*]+?)\s*\*\/\s*)?@font-face\s*{([^}]+)}/g)]
  const faces = []
  const saved = new Map() // Google serves one variable file for several weights: download it once.
  for (const [, label = '', body] of blocks) {
    const url = body.match(/url\((https:[^)]+)\)/)?.[1]
    const weight = body.match(/font-weight:\s*([^;]+);/)?.[1].trim()
    const style = body.match(/font-style:\s*([^;]+);/)?.[1].trim() ?? 'normal'
    const range = body.match(/unicode-range:\s*([^;]+);/)?.[1].trim()
    if (!url || !weight) throw new Error(`unexpected @font-face in ${spec.family}`)
    let name = saved.get(url)
    if (!name) {
      // CJK slices come without a subset comment: number them in the order Google lists them.
      name = `${style}-${label.replace(/[^a-z0-9]+/gi, '') || `s${String(saved.size).padStart(3, '0')}`}-${saved.size}.woff2`
      const data = await get(url)
      await writeFile(path.join(dir, name), data)
      saved.set(url, name)
      files++
      bytes += data.length
    }
    faces.push(`@font-face{font-family:'${spec.family}';font-style:${style};font-weight:${weight};font-display:swap;src:url(./${spec.dir}/${name}) format('woff2');${range ? `unicode-range:${range};` : ''}}`)
  }
  out[spec.css].push(`/* ${spec.family} (${faces.length} slices) */`, ...faces, `@font-face{font-family:'${spec.family} Fallback';${spec.fallback}}`)
  console.log(spec.family, faces.length, 'faces,', saved.size, 'files')
}

const header = '/* Generated by scripts/fetch-fonts.mjs — do not edit by hand. */\n'
await writeFile(path.join(ROOT, 'root.css'), header + out.root.join('\n') + '\n')
await writeFile(path.join(ROOT, 'hub.css'), header + out.hub.join('\n') + '\n')
console.log(`${files} files, ${(bytes / 1024 / 1024).toFixed(1)} MB`)
